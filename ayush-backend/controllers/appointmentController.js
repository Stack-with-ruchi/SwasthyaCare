// 2A. GET DOCTOR CASE DETAILS
// Doctor views patient + AI summary
// =====================================================

export const getDoctorCaseDetails = async (req, res) => {
  try {
    const { appointmentId } = req.params;

    const doctorIdentifier = getDoctorIdentifier(req);

    // ---------------------------------------------
    // Validate doctor identifier
    // ---------------------------------------------

    if (!doctorIdentifier?.trim()) {
      return res.status(400).json({
        success: false,
        message: "Doctor identifier is required.",
      });
    }

    // ---------------------------------------------
    // Find doctor
    // ---------------------------------------------

    const doctor = await findDoctorByIdentifier(doctorIdentifier);

    if (!doctor) {
      return res.status(404).json({
        success: false,
        message: "Doctor not found.",
      });
    }

    // ---------------------------------------------
    // Find appointment assigned to this doctor
    // ---------------------------------------------

    const appointment = await Appointment.findOne({
      _id: appointmentId,
      doctorId: doctor._id,
    })
      .populate("patientId", "fullName mobile email dob gender abhaId")
      .populate(
        "tokenCaseId",
        "tokenNumber hospitalName department crNumber summaryStatus aiSummary aiSummaryStatus patientApproved approvedForDoctorSharing patientReviewNote doctorEditedSummary doctorEditedAt doctorEditedBy summarySource",
      );

    if (!appointment) {
      return res.status(404).json({
        success: false,
        message: "Appointment/case not found for this doctor.",
      });
    }

    return res.status(200).json({
      success: true,

      appointment,

      patient: appointment.patientId,

      case: appointment.tokenCaseId,

      // ---------------------------------------------
      // Summary information
      // ---------------------------------------------

      summary: {
        aiSummary: appointment.tokenCaseId?.aiSummary?.fullSummary || "",

        doctorEditedSummary: appointment.tokenCaseId?.doctorEditedSummary || "",

        summarySource: appointment.tokenCaseId?.summarySource || "AI",

        doctorEditedAt: appointment.tokenCaseId?.doctorEditedAt || null,

        doctorEditedBy: appointment.tokenCaseId?.doctorEditedBy || null,
      },
    });
  } catch (error) {
    console.error("Get doctor case details error:", error);

    return res.status(500).json({
      success: false,
      message: "Failed to fetch doctor case details.",
      error: error.message,
    });
  }
};

// =====================================================
// 2B. SAVE DOCTOR-EDITED FINAL SUMMARY
// =====================================================

export const updateDoctorEditedSummary = async (req, res) => {
  try {
    const { appointmentId } = req.params;

    const { identifier, doctorEditedSummary } = req.body;

    // ---------------------------------------------
    // Validate doctor identifier
    // ---------------------------------------------

    if (!identifier?.trim()) {
      return res.status(400).json({
        success: false,
        message: "Doctor identifier is required.",
      });
    }

    // ---------------------------------------------
    // Validate summary
    // ---------------------------------------------

    if (
      typeof doctorEditedSummary !== "string" ||
      !doctorEditedSummary.trim()
    ) {
      return res.status(400).json({
        success: false,
        message: "Doctor-edited summary cannot be empty.",
      });
    }

    // ---------------------------------------------
    // Find doctor
    // ---------------------------------------------

    const doctor = await findDoctorByIdentifier(identifier);

    if (!doctor) {
      return res.status(404).json({
        success: false,
        message: "Doctor not found.",
      });
    }

    // ---------------------------------------------
    // Find appointment belonging to doctor
    // ---------------------------------------------

    const appointment = await Appointment.findOne({
      _id: appointmentId,
      doctorId: doctor._id,
    });

    if (!appointment) {
      return res.status(404).json({
        success: false,
        message: "Appointment/case not found for this doctor.",
      });
    }

    // ---------------------------------------------
    // Find linked TokenCase
    // ---------------------------------------------

    if (!appointment.tokenCaseId) {
      return res.status(404).json({
        success: false,
        message: "No case is linked to this appointment.",
      });
    }

    const tokenCase = await TokenCase.findOne({
      _id: appointment.tokenCaseId,
      doctorId: doctor._id,
    });

    if (!tokenCase) {
      return res.status(404).json({
        success: false,
        message: "Case not found for this doctor.",
      });
    }

    // ---------------------------------------------
    // SAVE COMPLETE FINAL SUMMARY
    // ---------------------------------------------

    tokenCase.doctorEditedSummary = doctorEditedSummary.trim();

    tokenCase.doctorEditedAt = new Date();

    tokenCase.doctorEditedBy = doctor._id;

    tokenCase.summarySource = "DoctorEdited";

    await tokenCase.save();

    return res.status(200).json({
      success: true,

      message: "Doctor-edited summary saved successfully.",

      summary: {
        aiSummary: tokenCase.aiSummary.fullSummary,

        doctorEditedSummary: tokenCase.doctorEditedSummary,

        summarySource: tokenCase.summarySource,

        doctorEditedAt: tokenCase.doctorEditedAt,

        doctorEditedBy: tokenCase.doctorEditedBy,
      },
    });
  } catch (error) {
    console.error("Update doctor-edited summary error:", error);

    return res.status(500).json({
      success: false,

      message: "Failed to save doctor-edited summary.",

      error: error.message,
    });
  }
};

// =====================================================
// 3. ACCEPT APPOINTMENT
// Doctor selects ONLY consultation time
// =====================================================

export const acceptAppointment = async (req, res) => {
  try {
    const { appointmentId } = req.params;

    const { identifier, appointmentTime } = req.body;

    // ---------------------------------------------
    // Validate doctor identifier
    // ---------------------------------------------

    if (!identifier?.trim()) {
      return res.status(400).json({
        success: false,
        message: "Doctor identifier is required.",
      });
    }

    // ---------------------------------------------
    // Validate consultation time
    // ---------------------------------------------

    if (!appointmentTime?.trim()) {
      return res.status(400).json({
        success: false,
        message: "Consultation time is required.",
      });
    }

    // ---------------------------------------------
    // Find doctor
    // ---------------------------------------------

    const doctor = await findDoctorByIdentifier(identifier);

    if (!doctor) {
      return res.status(404).json({
        success: false,
        message: "Doctor not found.",
      });
    }

    // ---------------------------------------------
    // Find pending appointment
    // ---------------------------------------------

    const appointment = await Appointment.findOne({
      _id: appointmentId,

      doctorId: doctor._id,

      status: "Pending",
    });

    if (!appointment) {
      return res.status(404).json({
        success: false,
        message: "Pending case request not found.",
      });
    }

    // ---------------------------------------------
    // Consultation date
    // Automatically set to today's date.
    // Doctor only chooses the time.
    // ---------------------------------------------

    const appointmentDate = new Date();

    appointmentDate.setHours(0, 0, 0, 0);

    // ---------------------------------------------
    // Check time conflict
    // ---------------------------------------------

    const conflictingAppointment = await Appointment.findOne({
      _id: {
        $ne: appointmentId,
      },

      doctorId: doctor._id,

      status: "Accepted",

      appointmentDate,

      appointmentTime: appointmentTime.trim(),
    });

    if (conflictingAppointment) {
      return res.status(409).json({
        success: false,

        message:
          "The doctor already has an appointment at this consultation time.",
      });
    }

    // ---------------------------------------------
    // Accept appointment
    // ---------------------------------------------

    appointment.status = "Accepted";

    appointment.appointmentDate = appointmentDate;

    appointment.appointmentTime = appointmentTime.trim();

    await appointment.save();

    // ---------------------------------------------
    // Update TokenCase
    // ---------------------------------------------

    if (appointment.tokenCaseId) {
      await TokenCase.findByIdAndUpdate(
        appointment.tokenCaseId,

        {
          doctorId: doctor._id,

          doctorAction: "Accepted",
        },

        {
          returnDocument: "after",
        },
      );
    }

    return res.status(200).json({
      success: true,

      message: "Appointment accepted successfully.",

      appointment,
    });
  } catch (error) {
    console.error("Accept appointment error:", error);

    return res.status(500).json({
      success: false,

      message: "Failed to accept appointment.",

      error: error.message,
    });
  }
};


import Appointment from "../models/Appointment.js";
import Doctor from "../models/Doctor.js";
import TokenCase from "../models/TokenCase.js";

// =====================================================
// HELPER: FIND DOCTOR FROM IDENTIFIER
// =====================================================

const findDoctorByIdentifier = async (identifier) => {
  if (!identifier?.trim()) {
    return null;
  }

  const normalizedIdentifier = identifier.trim();

  return await Doctor.findOne({
    $or: [
      { mobile: normalizedIdentifier },
      { email: normalizedIdentifier.toLowerCase() },
      { regNumber: normalizedIdentifier },
    ],
  });
};

// =====================================================
// HELPER: GET DOCTOR IDENTIFIER
// =====================================================

const getDoctorIdentifier = (req) => {
  return (
    req.query.identifier ||
    req.query.doctorIdentifier ||
    req.body?.identifier ||
    req.headers["x-doctor-identifier"] ||
    ""
  );
};

// =====================================================
// 1. CREATE CASE / APPOINTMENT REQUEST
// Patient submits Case Taking form
// =====================================================

export const createAppointment = async (req, res) => {
  try {
    const patientId = req.user.id;

    const { crNumber, tokenNumber, hospitalName, department, reason, consent } =
      req.body;

    // ---------------------------------------------
    // Validate required fields
    // ---------------------------------------------

    if (!crNumber?.trim()) {
      return res.status(400).json({
        success: false,
        message: "CR number is required.",
      });
    }

    if (!tokenNumber?.trim() || !hospitalName?.trim() || !department?.trim()) {
      return res.status(400).json({
        success: false,
        message: "Token number, hospital/clinic, and department are required.",
      });
    }

    // ---------------------------------------------
    // Validate data consent
    // ---------------------------------------------

    if (consent !== true) {
      return res.status(400).json({
        success: false,
        message: "Data sharing consent is required before submitting the case.",
      });
    }

    // ---------------------------------------------
    // Find doctor
    // ---------------------------------------------

    const doctor = await Doctor.findOne({
      hospitalClinic: hospitalName.trim(),
      department: department.trim(),
    });

    if (!doctor) {
      return res.status(404).json({
        success: false,
        message:
          "No doctor found for the selected hospital/clinic and department.",
      });
    }

    // ---------------------------------------------
    // Prevent duplicate active case
    // ---------------------------------------------

    const existingAppointment = await Appointment.findOne({
      patientId,
      tokenNumber: tokenNumber.trim(),
      hospitalName: hospitalName.trim(),
      department: department.trim(),
      status: {
        $in: ["Pending", "Accepted"],
      },
    });

    if (existingAppointment) {
      return res.status(400).json({
        success: false,
        message: "You already have an active case request for this token.",
      });
    }

    // ---------------------------------------------
    // Automatically store request date/time
    // ---------------------------------------------

    const requestDate = new Date();

    const requestTime = requestDate.toLocaleTimeString("en-IN", {
      hour: "2-digit",
      minute: "2-digit",
      hour12: true,
    });

    // ---------------------------------------------
    // Create TokenCase
    // ---------------------------------------------
    //
    // IMPORTANT:
    // CR number comes from the patient.
    // It is NOT generated by the backend.
    // ---------------------------------------------

    const tokenCase = await TokenCase.create({
      patientId,

      doctorId: doctor._id,

      hospitalName: hospitalName.trim(),

      department: department.trim(),

      tokenNumber: tokenNumber.trim(),

      crNumber: crNumber.trim(),

      // Patient gave consent during Case Taking
      dataConsent: {
        status: "Confirmed",
        confirmedAt: requestDate,
        sharedItems: ["Patient Details", "AI Summary", "Medical Reports"],
      },

      doctorAction: "Pending",

      summaryStatus: "AI summary Not available",
    });

    try {
      // ---------------------------------------------
      // Create Appointment / Case Request
      // ---------------------------------------------

      const appointment = await Appointment.create({
        patientId,

        doctorId: doctor._id,

        tokenCaseId: tokenCase._id,

        tokenNumber: tokenNumber.trim(),

        hospitalName: hospitalName.trim(),

        department: department.trim(),

        // Automatically stored request information
        requestDate,

        requestTime,

        // Consultation information will be added
        // when doctor accepts the case
        appointmentDate: null,

        appointmentTime: null,

        reason: reason?.trim() || "",

        status: "Pending",
      });

      return res.status(201).json({
        success: true,

        message: "Case submitted successfully.",

        appointment,

        case: {
          crNumber: tokenCase.crNumber,
          tokenNumber: tokenCase.tokenNumber,
          hospitalName: tokenCase.hospitalName,
          department: tokenCase.department,
        },

        request: {
          requestDate,

          requestTime,
        },
      });
    } catch (appointmentError) {
      // If Appointment creation fails,
      // remove TokenCase.
      await TokenCase.findByIdAndDelete(tokenCase._id);

      throw appointmentError;
    }
  } catch (error) {
    console.error("Create case request error:", error);

    return res.status(500).json({
      success: false,

      message: "Failed to submit case request.",

      error: error.message,
    });
  }
};

// =====================================================
// 2. GET ALL APPOINTMENTS ASSIGNED TO DOCTOR
// =====================================================

export const getDoctorAppointments = async (req, res) => {
  try {
    const doctorIdentifier = getDoctorIdentifier(req);

    if (!doctorIdentifier) {
      return res.status(400).json({
        success: false,
        message: "Doctor identifier is required.",
      });
    }

    // ---------------------------------------------
    // Find doctor
    // ---------------------------------------------

    const doctor = await findDoctorByIdentifier(doctorIdentifier);

    if (!doctor) {
      return res.status(404).json({
        success: false,
        message: "Doctor not found.",
      });
    }

    // ---------------------------------------------
    // Get doctor's appointments
    // ---------------------------------------------

    const appointments = await Appointment.find({
      doctorId: doctor._id,
    })
      .populate("patientId", "fullName mobile email dob gender abhaId")
      .populate(
        "tokenCaseId",
        "tokenNumber hospitalName department summaryStatus dataConsent doctorAction crNumber aiSummary",
      )
      .sort({
        status: 1,
        requestDate: -1,
        createdAt: -1,
      });

    return res.status(200).json({
      success: true,

      totalAppointments: appointments.length,

      appointments,

      todayAppointments: appointments,
    });
  } catch (error) {
    console.error("Get doctor appointments error:", error);

    return res.status(500).json({
      success: false,

      message: "Failed to fetch doctor appointments.",

      error: error.message,
    });
  }
};

